import time

# =====================================================================
# تجربة عمليّة: مقارنة السرعة بين الطريقة التقليدية وقفيز حسّون اللوغاريتمي
# المبرهنة المثبتة بـ Lean 4:  b^(2^m) * x^(2^m * n) = (x - a)^(2^m)
# =====================================================================

# 1. تحديد معطيات الشرط المحقق (x = a + b * x^n)
a = -2
b = 1
n = 2
x = 2  # الشرط محقق: 2 = -2 + 1 * (2)^2

# باقي القسمة المعياري (Mersenne Modulo M31)
M = 2**31 - 1

# عدد عمليات القفز اللوغاريتمي (m = 25)
# 2^25 تعني قفز 33,554,432 خطوة تكرارية كاملة!
m = 25
k = 2**m

print("=" * 65)
print(f"🚀 بداية تجربة تسريع الحسابات التكرارية")
print(f"🔹 عدد الخطوات التكرارية المطلوبة (k): {k:,} خطوة (33.5 مليون خطوة)")
print("=" * 65)

# ---------------------------------------------------------------------
# 1. الطريقة التقليدية (Linear Loop O(k)) - خطوة بخطوة
# ---------------------------------------------------------------------
print("\n[1] جاري التشغيل بالطريقة التقليدية (تكرار 33.5 مليون خطوة خطوة بخطوة)...")
start_time = time.time()

# حساب متكرر خطوة بخطوة (O(k))
base = (b * (x**n)) % M
val_trad = 1
for _ in range(k):
    val_trad = (val_trad * base) % M

time_trad = time.time() - start_time
print(f"⏱️ الزمن المستغرق بالطريقة التقليدية: {time_trad:.4f} ثانية")


# ---------------------------------------------------------------------
# 2. طريقة قفز حسّون اللوغاريتمي (Hassoun Jump O(log k)) - m عمليات فقط!
# ---------------------------------------------------------------------
print("\n[2] جاري التشغيل بطريقة قفز حسّون اللوغاريتمي (25 عملية تربيع فقط)...")
start_time = time.time()

# تطبيق مبرهنة حسّون: (x - a)^(2^m) mod M
# القيام بـ m = 25 عملية تربيع فقط!
val_hassoun = (x - a) % M
for _ in range(m):  # 25 دورة فقط بدلاً من 33.5 مليون!
    val_hassoun = (val_hassoun * val_hassoun) % M

time_hassoun = time.time() - start_time
print(f"⏱️ الزمن المستغرق بطريقة قفز حسّون: {time_hassoun:.8f} ثانية")


# ---------------------------------------------------------------------
# النتيجة والتحقق من التطابق
# ---------------------------------------------------------------------
print("\n" + "=" * 65)
print(f"🔎 التحقق من صحة النتيجة الرياضياتية:")
print(f" - نتيجة الطريقة التقليدية: {val_trad}")
print(f" - نتيجة طريقة قفز حسّون   : {val_hassoun}")

if val_trad == val_hassoun:
    print("✅ النتيجتان متطابقتان تماماً وبدقة 100%!")

speedup = time_trad / time_hassoun if time_hassoun > 0 else 0
print(f"\n⚡ نسبة التسريع الفعلي (Speedup Factor):")
print(f" طريقتك أسرع بـ {speedup:,.0f} مرة من الطريقة التقليدية!")
print("=" * 65)